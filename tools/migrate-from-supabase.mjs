#!/usr/bin/env node
// ============================================================
// Copy everything from the Supabase version of RMA Blaster into
// the Cloudflare one: all entries, all files, the email queue and the
// change history. Ids and dates are kept exactly, so links between an
// entry, its files and its original email survive the move.
//
// It only READS from Supabase. Nothing there is changed.
//
// Two steps, run from the repo folder:
//
//   1. Download a full copy to this computer:
//        SUPABASE_SECRET_KEY=...  node tools/migrate-from-supabase.mjs fetch
//
//   2. Load that copy into Cloudflare (or into the local test database):
//        node tools/migrate-from-supabase.mjs load --remote
//        node tools/migrate-from-supabase.mjs load --local
//
// The key for step 1 is in the Supabase dashboard under
// Project Settings, API Keys, "Secret keys". It can read everything,
// so do not paste it anywhere but your own terminal, and never commit it.
//
// Step 2 REPLACES what is in the Cloudflare database with the copy.
// That is what you want before the team switches over, and exactly what
// you do not want afterwards. It asks you to confirm.
//
// Both steps are safe to run again. Files already downloaded or already
// uploaded are skipped. The copy lives in .migration/, which git ignores.
// ============================================================

import { spawn } from 'node:child_process';
import { createInterface } from 'node:readline/promises';
import { mkdir, readFile, writeFile, stat } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT     = join(dirname(fileURLToPath(import.meta.url)), '..');
const WORK     = join(ROOT, '.migration');
const SUPABASE = 'https://oyspjwnhzpczmumftris.supabase.co';
const BUCKET   = 'rma-pdfs';
const DATABASE = 'rma-blaster-db';      // must match wrangler.toml
const R2       = 'rma-blaster-files';   // must match wrangler.toml

// D1 refuses a single SQL statement over 100 KB. One email body is the only
// thing that could get near that, so it is capped well below.
const MAX_BODY_BYTES = 60000;

// ---- building the SQL (exported so tests/migrate.test.mjs can check it) ----

function sqlValue(value) {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : 'NULL';
  if (typeof value === 'boolean') return value ? '1' : '0';
  // Doubling the quote is the whole of SQLite's string escaping. NUL bytes
  // cannot be stored in a text literal, so drop them.
  return `'${String(value).replace(/\u0000/g, '').replace(/'/g, "''")}'`;
}

// Postgres writes "2026-08-20T12:00:00.123456+00:00". The Worker compares
// timestamps as text, which only works if they are all in one format.
function isoTime(value) {
  if (!value) return null;
  const t = new Date(value);
  return isNaN(t.getTime()) ? String(value) : t.toISOString();
}

function capBytes(text, max) {
  if (text === null || text === undefined) return text;
  const buf = Buffer.from(String(text), 'utf8');
  if (buf.length <= max) return String(text);
  // Cut on a character boundary, not in the middle of one.
  return new TextDecoder('utf-8', { fatal: false }).decode(buf.subarray(0, max)).replace(/�+$/, '');
}

const TABLES = {
  entries: {
    columns: ['id', 'email_id', 'rma_number', 'date', 'dealer', 'make', 'model', 'serial_number',
              'issue_description', 'issue_confirmed', 'warranty_status', 'course_of_action',
              'date_of_resolution', 'how_resolved', 'notes', 'replaced_from', 'status',
              'flags', 'deleted', 'deleted_at', 'imported_at', 'last_modified'],
    times: ['deleted_at', 'imported_at', 'last_modified']
  },
  pdfs: {
    columns: ['id', 'entry_id', 'filename', 'type', 'storage_path', 'saved_at'],
    times: ['saved_at']
  },
  pending_emails: {
    columns: ['id', 'message_id', 'subject', 'from_address', 'sent_at', 'text_body', 'attachments',
              'status', 'error', 'entry_id', 'received_at', 'processed_at'],
    times: ['received_at', 'processed_at']
  },
  // Who changed what, written by the Supabase trigger. Copied exactly,
  // ids included, so the record is unbroken across the move.
  entry_history: {
    columns: ['id', 'entry_id', 'rma_number', 'changed_at', 'user_id', 'user_email',
              'action', 'field', 'old_value', 'new_value'],
    times: ['changed_at']
  }
};

export function buildSql(data) {
  const lines = [
    '-- Generated by tools/migrate-from-supabase.mjs. Replaces everything.',
    // Children first, so no row is ever left pointing at a deleted parent.
    'DELETE FROM entry_history;',
    'DELETE FROM pending_emails;',
    'DELETE FROM pdfs;',
    'DELETE FROM entries;'
  ];
  for (const [table, { columns, times }] of Object.entries(TABLES)) {
    for (const row of data[table] || []) {
      const values = columns.map(col => {
        let value = row[col];
        if (times.includes(col)) value = isoTime(value);
        if (col === 'attachments') value = JSON.stringify(Array.isArray(value) ? value : []);
        if (col === 'text_body') value = capBytes(value, MAX_BODY_BYTES);
        // An entry Supabase never had a flags column for still needs a value.
        if (col === 'flags' && value == null) value = '';
        return sqlValue(value);
      });
      lines.push(`INSERT INTO ${table} (${columns.join(', ')}) VALUES (${values.join(', ')});`);
    }
  }
  return lines.join('\n') + '\n';
}

// Every stored file the database refers to: entry files, plus attachments
// still sitting in the queue's holding area.
//
// Only queue rows that are not finished yet. Once the app imports an email
// it moves the attachments into the entry and deletes the holding copies,
// but the queue row still lists where they used to be. Asking for those
// gets a "not found" for every RMA ever imported, which is expected and
// would bury a real problem in noise.
const FINISHED = ['processed', 'ignored'];

export function filePaths(data) {
  const paths = new Set();
  for (const pdf of data.pdfs || []) if (pdf.storage_path) paths.add(pdf.storage_path);
  for (const mail of data.pending_emails || []) {
    if (FINISHED.includes(mail.status)) continue;
    for (const att of (Array.isArray(mail.attachments) ? mail.attachments : [])) {
      if (att && att.storagePath && att.storagePath.startsWith('pending/')) paths.add(att.storagePath);
    }
  }
  return [...paths].sort();
}

export function contentTypeFor(path) {
  const ext = path.toLowerCase().split('.').pop();
  return { pdf: 'application/pdf', jpg: 'image/jpeg', jpeg: 'image/jpeg', png: 'image/png' }[ext]
      || 'application/octet-stream';
}

// ---- step 1: fetch ----

async function exists(path) {
  try { await stat(path); return true; } catch (_) { return false; }
}

async function fetchTable(table, key) {
  const rows = [];
  const page = 1000;
  for (let offset = 0; ; offset += page) {
    const res = await fetch(`${SUPABASE}/rest/v1/${table}?select=*&order=id&limit=${page}&offset=${offset}`,
      { headers: { apikey: key, Authorization: `Bearer ${key}` } });
    if (!res.ok) {
      const hint = res.status === 401 || res.status === 403
        ? ' The key was refused. It must be a SECRET key, not the publishable one.' : '';
      throw new Error(`Reading ${table} failed (${res.status}).${hint} ${(await res.text()).slice(0, 200)}`);
    }
    const batch = await res.json();
    rows.push(...batch);
    if (batch.length < page) return rows;
  }
}

async function fetchFile(path, key) {
  const target = join(WORK, 'files', path);
  if (await exists(target)) return 'had';
  const url = `${SUPABASE}/storage/v1/object/${BUCKET}/${path.split('/').map(encodeURIComponent).join('/')}`;
  const res = await fetch(url, { headers: { apikey: key, Authorization: `Bearer ${key}` } });
  if (!res.ok) return `HTTP ${res.status}`;
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, Buffer.from(await res.arrayBuffer()));
  return 'new';
}

async function stepFetch() {
  const key = process.env.SUPABASE_SECRET_KEY;
  if (!key) {
    throw new Error('Set SUPABASE_SECRET_KEY first. See the notes at the top of this file.');
  }
  await mkdir(WORK, { recursive: true });

  const data = {};
  for (const table of Object.keys(TABLES)) {
    data[table] = await fetchTable(table, key);
    console.log(`  ${String(data[table].length).padStart(5)}  ${table}`);
  }

  const paths = filePaths(data);
  const missing = [];
  let fresh = 0;
  for (let i = 0; i < paths.length; i++) {
    process.stdout.write(`\r  downloading file ${i + 1} of ${paths.length}   `);
    const result = await fetchFile(paths[i], key);
    if (result === 'new') fresh++;
    else if (result !== 'had') missing.push(`${paths[i]} (${result})`);
  }
  console.log(`\r  ${String(paths.length - missing.length).padStart(5)}  files (${fresh} downloaded just now)      `);

  await writeFile(join(WORK, 'rows.json'), JSON.stringify(data));
  await writeFile(join(WORK, 'data.sql'), buildSql(data));
  await writeFile(join(WORK, 'files.json'),
    JSON.stringify(paths.filter(p => !missing.some(m => m.startsWith(p + ' ')))));

  if (missing.length) {
    console.log(`\n${missing.length} file(s) are listed in the database but could not be downloaded:`);
    for (const m of missing) console.log('   ' + m);
    console.log('Their rows are still copied. The files themselves will be missing in the new app too.');
  }
  console.log('\nCopy saved in .migration/. Next:  node tools/migrate-from-supabase.mjs load --local   (or --remote)');
}

// ---- step 2: load ----

function wrangler(args) {
  return new Promise((resolve, reject) => {
    const child = spawn('npx', ['wrangler', ...args], { cwd: ROOT, stdio: ['ignore', 'pipe', 'pipe'] });
    let output = '';
    child.stdout.on('data', chunk => { output += chunk; });
    child.stderr.on('data', chunk => { output += chunk; });
    child.on('error', reject);
    child.on('close', code => code === 0
      ? resolve(output)
      : reject(new Error(`wrangler ${args.slice(0, 3).join(' ')} failed:\n${output.trim().split('\n').slice(-12).join('\n')}`)));
  });
}

async function stepLoad(target) {
  if (target !== '--local' && target !== '--remote') {
    throw new Error('Say where to load it: --local (test database on this computer) or --remote (Cloudflare).');
  }
  if (!await exists(join(WORK, 'data.sql'))) {
    throw new Error('Nothing to load yet. Run the fetch step first.');
  }
  const data  = JSON.parse(await readFile(join(WORK, 'rows.json'), 'utf8'));
  const paths = JSON.parse(await readFile(join(WORK, 'files.json'), 'utf8'));
  const where = target === '--remote' ? 'the LIVE Cloudflare database' : 'the local test database';

  console.log(`About to replace everything in ${where} with the copy in .migration/:`);
  console.log(`  ${data.entries.length} entries, ${data.pdfs.length} file records, ` +
              `${data.pending_emails.length} queue rows, ${data.entry_history.length} history rows, ` +
              `${paths.length} files`);
  if (target === '--remote' && !process.argv.includes('--yes')) {
    const rl = createInterface({ input: process.stdin, output: process.stdout });
    const answer = await rl.question('Anything entered in the new app since the last load will be lost. Type REPLACE to continue: ');
    rl.close();
    if (answer.trim() !== 'REPLACE') { console.log('Stopped. Nothing was changed.'); return; }
  }

  console.log('Loading rows...');
  await wrangler(['d1', 'execute', DATABASE, target, '--yes', '--file', join(WORK, 'data.sql')]);

  // Remember what has been uploaded, per target, so a second run is quick.
  const donePath = join(WORK, `uploaded${target}.json`);
  const done = new Set(await exists(donePath) ? JSON.parse(await readFile(donePath, 'utf8')) : []);
  const todo = paths.filter(p => !done.has(p));
  const failed = [];
  let finished = 0;

  // The local database is a single file and does not like being written
  // to from several processes at once. Cloudflare does not mind.
  const lanes = target === '--remote' ? 4 : 1;
  const next = async () => {
    while (todo.length) {
      const path = todo.shift();
      try {
        await wrangler(['r2', 'object', 'put', `${R2}/${path}`, target,
                        '--file', join(WORK, 'files', path), '--content-type', contentTypeFor(path)]);
        done.add(path);
      } catch (err) {
        failed.push(`${path}: ${err.message.split('\n').pop()}`);
      }
      process.stdout.write(`\r  uploading files: ${++finished} done, ${todo.length} to go   `);
    }
  };
  await Promise.all(Array.from({ length: lanes }, next));
  await writeFile(donePath, JSON.stringify([...done]));
  console.log(`\r  ${done.size} of ${paths.length} files are in place.                    `);

  if (failed.length) {
    console.log(`\n${failed.length} file(s) failed to upload. Run the same command again to retry just those:`);
    for (const f of failed.slice(0, 20)) console.log('   ' + f);
    process.exitCode = 1;
    return;
  }
  console.log('Done.');
}

// ---- entry point (skipped when the tests import this file) ----

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const [step, target] = process.argv.slice(2);
  const run = step === 'fetch' ? stepFetch() : step === 'load' ? stepLoad(target)
    : Promise.reject(new Error('Usage: node tools/migrate-from-supabase.mjs fetch | load --local | load --remote'));
  run.catch(err => { console.error('\n' + err.message); process.exit(1); });
}
